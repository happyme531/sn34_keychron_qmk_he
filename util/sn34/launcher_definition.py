"""Generate BAT68 definitions for the official Keychron Launcher JSON loader.

Uses the native definition shape served by Launcher for Keychron Q1 HE:
https://launcher.keychron.com/static/device/875825936/json/v3.json
HE pages and their protocol implementation remain in the official web app.
"""
import json
import os
from pathlib import Path
import re
import subprocess
from build_config import ROOT, board_directory, write_if_changed
from model import load_board


def generate_launcher_definition(root, build, qmk, newlib=None):
    board=load_board();unit=board["layout_unit"]
    target=json.loads((board_directory()/"target.json").read_text(encoding="utf-8"))
    if not target["features"]["rgb"]:
        protocol=[dict(wire=0,core=0,name="NONE",label="None")]
        write_if_changed(build/"rgb_effects.json","[]")
        write_if_changed(build/"rgb_protocol.json",json.dumps(protocol,indent=2))
        write_if_changed(build/"rgb_protocol.generated.h", "#pragma once\nstatic const uint8_t sn34_rgb_wire_to_core[]={0};\nstatic const uint8_t sn34_rgb_core_to_wire[]={0};\n")
        write_definitions(board,build,[])
        return
    compiler = [os.environ.get("SN34_CC", "arm-none-eabi-gcc")]
    source = '#include "config.h"\n#define RGB_MATRIX_KEYREACTIVE_ENABLED\n#define RGB_MATRIX_EFFECT(name) SN34_EFFECT_##name\n#include "quantum/rgb_matrix/animations/rgb_matrix_effects.inc"\n'
    command = compiler + ["-DRGB_MATRIX_ENABLE", "-E", "-P", "-x", "c", "-"]
    for path in (build, board_directory().parent, root / "platforms/sn34/include", root / "drivers/led",
                 root / "drivers/analog/keychron_he", qmk / "keyboards/keychron/common/analog_matrix", qmk,
                 newlib):
        command += ["-I", str(path)]
    processed = subprocess.check_output(command, input=source, text=True)
    effects = re.findall(r"SN34_EFFECT_(\w+)", processed)
    assert effects and effects[0] == "SOLID_COLOR" and len(effects) == len(set(effects))
    # Launcher translates unknown labels by numeric ID. Its first 22 IDs are
    # fixed; 23/24 are special per-key/mixed editors that we do not implement.
    canonical = """SOLID_COLOR BREATHING BAND_SPIRAL_VAL CYCLE_ALL CYCLE_LEFT_RIGHT
        CYCLE_UP_DOWN RAINBOW_MOVING_CHEVRON CYCLE_OUT_IN CYCLE_OUT_IN_DUAL
        CYCLE_PINWHEEL CYCLE_SPIRAL DUAL_BEACON RAINBOW_BEACON JELLYBEAN_RAINDROPS
        PIXEL_RAIN TYPING_HEATMAP DIGITAL_RAIN SOLID_REACTIVE_SIMPLE
        SOLID_REACTIVE_MULTIWIDE SOLID_REACTIVE_MULTINEXUS SPLASH SOLID_SPLASH""".split()
    assert all(name in effects for name in canonical)
    protocol = [dict(wire=0, core=0, name="NONE", label="None")]
    for wire, name in list(enumerate(canonical, 1)) + list(enumerate([n for n in effects if n not in canonical], 25)):
        label = name.replace("_", " ").title()
        if name.startswith("SOLID_REACTIVE_") and name in canonical:
            label = label.removeprefix("Solid ")
        protocol.append(dict(wire=wire, core=effects.index(name) + 1, name=name, label=label))
    options = [[item["label"], item["wire"]] for item in protocol]
    wire_to_core = [255] * (max(item["wire"] for item in protocol) + 1)
    core_to_wire = [0] * (len(effects) + 1)
    for item in protocol:
        wire_to_core[item["wire"]] = item["core"]
        core_to_wire[item["core"]] = item["wire"]
    header = "// Generated by util/sn34/launcher_definition.py; EEPROM keeps QMK core IDs.\n#pragma once\n"
    header += "static const uint8_t sn34_rgb_wire_to_core[]={" + ",".join(map(str, wire_to_core)) + "};\n"
    header += "static const uint8_t sn34_rgb_core_to_wire[]={" + ",".join(map(str, core_to_wire)) + "};\n"
    write_if_changed(build / "rgb_protocol.generated.h",header)
    write_if_changed(build / "rgb_protocol.json",json.dumps(protocol, indent=2))
    controls = [
        dict(label="Brightness", type="range", options=[0, 255], content=["id_qmk_rgb_matrix_brightness", 3, 1]),
        dict(label="Effect", type="dropdown", options=options, content=["id_qmk_rgb_matrix_effect", 3, 2]),
        dict(label="Effect Speed", type="range", options=[0, 255], content=["id_qmk_rgb_matrix_effect_speed", 3, 3]),
        dict(label="Color", type="color", content=["id_qmk_rgb_matrix_color", 3, 4]),
    ]
    menus = [dict(label="Lighting", content=[dict(label="Backlight", content=controls)])]
    write_definitions(board,build,menus)
    write_if_changed(build / "rgb_effects.json",json.dumps(effects, indent=2))


def write_definitions(board,build,menus):
    unit=board["layout_unit"]
    via = json.loads((build / "sn34_via.json").read_text(encoding="utf-8"))
    # Wire IDs match Launcher's translation dictionary, independently of the
    # compiled QMK enum. Both web configurators use this explicit menu.
    via["menus"] = menus
    via["keycodes"] = ["qmk_lighting"] if menus else []
    via["firmwareVersion"] = 5
    write_if_changed(build / "sn34_via.json",json.dumps(via, indent=2))
    mapping = json.loads((build / "board.json").read_text(encoding="utf-8"))
    keys = []
    for key in sorted(mapping, key=lambda k: (k["rect"][1], k["rect"][0])):
        x, y, w, h = key["rect"]
        row, col = key["matrix"]
        keys.append(dict(row=row, col=col, x=round(x / unit, 3), y=round(y / unit, 3),
                         r=0, rx=0, ry=0, d=False, w=round((w + 4) / unit, 3),
                         h=round((h + 4) / unit, 3), color="alpha"))
    definition = dict(name=via["name"], vendorId=via["vendorId"], productId=via["productId"],
                      vendorProductId=(int(via["vendorId"], 0) << 16) | int(via["productId"], 0), firmwareVersion=5,
                      feature=["HE"], accuration=0.1, menus=menus, keycodes=["qmk_lighting"] if menus else [],
                      customKeycodes=[], matrix=via["matrix"], layers=[layer["label"] for layer in board["layers"]],
                      layouts=dict(width=max(k["x"] + k["w"] for k in keys),
                                   height=max(k["y"] + k["h"] for k in keys), optionKeys={}, keys=keys))
    write_if_changed(build / "sn34_launcher.json",json.dumps(definition, indent=2))
